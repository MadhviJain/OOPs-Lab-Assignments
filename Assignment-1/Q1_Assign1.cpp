#include <iostream>
using namespace std;

int main()
{
    cout << "Hello World" << endl;

    // New line
    cout << "Hello\nWorld" << endl;

    // Tab
    cout << "Name\tRoll No\tDegree" << endl;

    // Alarm sound
    cout << "Alarm\a" << endl;

    // Carriage return
    cout << "Hello World\rHi" << endl;

    return 0;
}